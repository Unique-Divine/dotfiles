import { basename, dirname, resolve } from "node:path"
import { Command } from "commander"

import { cursorMcpConfigPath, readCursorMcpServers } from "../codex/config.ts"
import { isJsonObject, readJsonObject, type JsonObject } from "./settings.ts"

/**
 * Syncs Cursor MCP servers into Claude Code's user scope.
 *
 * Each Cursor stdio server becomes a Claude entry that runs `mcp-launch.ts`,
 * which reads the server definition from the Cursor config at startup. The
 * Claude entry holds no `env`, so secrets stay in `$HOME/.cursor/mcp.json`
 * and nothing this script writes or prints contains them.
 *
 * Writes go through `claude mcp add-json` and `claude mcp remove` because
 * Claude Code rewrites `$HOME/.claude.json` on its own; editing that file
 * directly could race with a running session.
 */

/** Claude Code stdio entry that starts a server through the launcher. */
export interface LauncherEntry {
  type: "stdio"
  command: string
  args: string[]
}

/** Paths baked into generated entries. */
export interface LauncherContext {
  bunPath: string
  launcherPath: string
  sourcePath: string
}

export interface McpPlan {
  add: { name: string; entry: LauncherEntry }[]
  update: { name: string; entry: LauncherEntry; replacesUnmanaged: boolean }[]
  remove: string[]
  skip: { name: string; reason: string }[]
}

export const claudeConfigPath = (
  env: NodeJS.ProcessEnv = process.env,
): string => {
  const home = env.HOME

  if (!home) {
    throw new Error("HOME is not set")
  }

  return resolve(home, ".claude.json")
}

export const defaultLauncherContext = (
  sourcePath: string = cursorMcpConfigPath(),
): LauncherContext => ({
  bunPath: process.execPath,
  launcherPath: resolve(import.meta.dir, "mcp-launch.ts"),
  sourcePath: resolve(sourcePath),
})

export const launcherEntry = (
  name: string,
  ctx: LauncherContext,
): LauncherEntry => ({
  type: "stdio",
  command: ctx.bunPath,
  args: [ctx.launcherPath, "--source", ctx.sourcePath, name],
})

/**
 * Reports whether a Claude entry was generated by this script. Matching on
 * `claude/mcp-launch.ts` rather than the full path keeps entries from a moved
 * checkout recognizable, so the next sync replaces or removes them.
 */
export const isLauncherEntry = (entry: unknown): boolean => {
  if (!isJsonObject(entry) || !Array.isArray(entry.args)) {
    return false
  }

  const script = entry.args[0]

  return (
    typeof script === "string" &&
    basename(script) === "mcp-launch.ts" &&
    basename(dirname(script)) === "claude"
  )
}

const sameEntry = (current: unknown, desired: LauncherEntry): boolean => {
  if (!isJsonObject(current)) {
    return false
  }

  const env = current.env

  return (
    (current.type ?? "stdio") === desired.type &&
    current.command === desired.command &&
    JSON.stringify(current.args) === JSON.stringify(desired.args) &&
    (env === undefined || (isJsonObject(env) && Object.keys(env).length === 0))
  )
}

const byName = ([a]: [string, unknown], [b]: [string, unknown]): number =>
  a.localeCompare(b)

export const planMcpSync = (
  cursorServers: Record<string, unknown>,
  claudeServers: Record<string, unknown>,
  ctx: LauncherContext,
): McpPlan => {
  const plan: McpPlan = { add: [], update: [], remove: [], skip: [] }
  const synced = new Set<string>()

  for (const [name, server] of Object.entries(cursorServers).sort(byName)) {
    if (!isJsonObject(server) || typeof server.command !== "string") {
      // Remote servers carry credentials in headers; copying them would
      // duplicate secrets, so they are left for `claude mcp add`.
      plan.skip.push({ name, reason: "no stdio command" })
      continue
    }

    synced.add(name)
    const entry = launcherEntry(name, ctx)
    const current = claudeServers[name]

    if (current === undefined) {
      plan.add.push({ name, entry })
    } else if (!sameEntry(current, entry)) {
      plan.update.push({
        name,
        entry,
        replacesUnmanaged: !isLauncherEntry(current),
      })
    }
  }

  for (const [name, entry] of Object.entries(claudeServers).sort(byName)) {
    if (!synced.has(name) && isLauncherEntry(entry)) {
      plan.remove.push(name)
    }
  }

  return plan
}

export const hasChanges = (plan: McpPlan): boolean =>
  plan.add.length + plan.update.length + plan.remove.length > 0

/** `claude` CLI invocations that apply a plan, in order. */
export const planCommands = (
  plan: McpPlan,
  claudeBin = "claude",
): string[][] => {
  const remove = (name: string) =>
    [claudeBin, "mcp", "remove", "--scope", "user", name]
  const add = (name: string, entry: LauncherEntry) => [
    claudeBin, "mcp", "add-json", "--scope", "user", name,
    JSON.stringify(entry),
  ]

  return [
    ...plan.remove.map(remove),
    ...plan.update.flatMap(({ name, entry }) => [remove(name), add(name, entry)]),
    ...plan.add.map(({ name, entry }) => add(name, entry)),
  ]
}

/** One line per planned change. Lines carry server names only. */
export const describePlan = (plan: McpPlan): string[] => [
  ...plan.add.map(({ name }) => `+ add ${name}`),
  ...plan.update.map(({ name, replacesUnmanaged }) =>
    replacesUnmanaged
      ? `~ replace ${name} (unmanaged Claude entry)`
      : `~ update ${name}`,
  ),
  ...plan.remove.map((name) => `- remove ${name}`),
  ...plan.skip.map(({ name, reason }) => `! skip ${name}: ${reason}`),
]

export const readClaudeUserMcpServers = async (
  path: string,
): Promise<JsonObject> => {
  const { config } = await readJsonObject(path)
  const servers = config.mcpServers ?? {}

  if (!isJsonObject(servers)) {
    throw new Error(`${path} mcpServers must be an object`)
  }

  return servers
}

const runCommands = async (commands: string[][]): Promise<void> => {
  for (const cmd of commands) {
    // Argument vectors avoid shell quoting of the JSON payload.
    const proc = Bun.spawn(cmd, { stdout: "pipe", stderr: "pipe" })
    const [exitCode, stderr] = await Promise.all([
      proc.exited,
      new Response(proc.stderr).text(),
    ])

    if (exitCode !== 0) {
      throw new Error(
        `${cmd.slice(0, 3).join(" ")} ${cmd[5]} failed (${exitCode}): ` +
          stderr.trim(),
      )
    }
  }
}

interface McpOptions {
  check?: boolean
  claudeConfig?: string
  dryRun?: boolean
  mcpSource?: string
  print?: boolean
  quiet?: boolean
  run?: boolean
}

export const createProgram = (): Command => {
  const program = new Command()

  program
    .name("claude-mcp")
    .description(
      "Register Cursor MCP servers in Claude Code's user scope through a " +
        "launcher that keeps their env in the Cursor config.",
    )
    .option("--run", "apply the plan with the claude CLI")
    .option("--dry-run", "print the plan without changing anything")
    .option("--check", "exit with code 1 if the plan has changes")
    .option("--print", "print the generated Claude entries as JSON")
    .option(
      "--mcp-source <path>",
      "read Cursor MCP servers from this JSON file",
    )
    .option(
      "--claude-config <path>",
      "read current Claude user servers from this JSON file",
    )
    .option("--quiet", "suppress normal output with --run")
    .action(async (options: McpOptions) => {
      const hasAction =
        options.run || options.dryRun || options.check || options.print

      if (!hasAction) {
        program.outputHelp()
        return
      }

      const ctx = defaultLauncherContext(
        options.mcpSource ?? cursorMcpConfigPath(),
      )
      const cursorServers = await readCursorMcpServers(ctx.sourcePath)
      const claudeServers = await readClaudeUserMcpServers(
        options.claudeConfig ?? claudeConfigPath(),
      )
      const plan = planMcpSync(cursorServers, claudeServers, ctx)

      if (options.print) {
        const entries = Object.fromEntries(
          Object.keys(cursorServers)
            .filter((name) => !plan.skip.some((s) => s.name === name))
            .sort()
            .map((name) => [name, launcherEntry(name, ctx)]),
        )
        process.stdout.write(`${JSON.stringify(entries, null, 2)}\n`)
        return
      }

      const lines = describePlan(plan)

      if (!options.quiet || !options.run) {
        if (hasChanges(plan)) {
          console.log("Claude Code MCP servers differ from the Cursor config:")
        } else {
          console.log("Claude Code MCP servers are already current")
        }

        for (const line of lines) console.log(line)
      }

      if (options.check) {
        if (hasChanges(plan)) process.exitCode = 1
        return
      }

      if (options.run && !options.dryRun && hasChanges(plan)) {
        await runCommands(planCommands(plan))
      }
    })

  return program
}

if (import.meta.main) {
  await createProgram().parseAsync()
}
