import { basename, dirname, resolve } from "node:path"
import { parse } from "smol-toml"

import { runtimeConfigPath } from "../codex/config.ts"

/**
 * Shared MCP model for the dotfiles sync.
 *
 * `~/.codex/config.toml` `[mcp_servers]` is the leader. Claude Code and the
 * Cursor CLI receive generated entries:
 *
 * - A stdio server becomes a launcher entry that runs `claude/mcp-launch.ts`.
 *   The launcher reads `command`, `args`, `env`, and `cwd` from the Codex
 *   file when the tool starts the server, so secrets stay in one file.
 * - A url server is copied as is, with Codex field names mapped to JSON ones.
 *
 * Every function here is pure except `readCodexMcpServers`.
 */

export type McpServer = Record<string, unknown>
export type McpServers = Record<string, McpServer>

/** Tool that receives generated entries. Entry shapes differ slightly. */
export type McpTarget = "claude" | "cursor"

export const codexConfigPath = runtimeConfigPath

export const isRecord = (value: unknown): value is McpServer =>
  typeof value === "object" && value !== null && !Array.isArray(value)

const isStringArray = (value: unknown): value is string[] =>
  Array.isArray(value) && value.every((entry) => typeof entry === "string")

export const isStringRecord = (
  value: unknown,
): value is Record<string, string> =>
  isRecord(value) &&
  Object.values(value).every((entry) => typeof entry === "string")

/**
 * Reads enabled `[mcp_servers]` entries from a Codex config. A missing file or
 * table yields `{}`. Errors name the path and server, never values.
 */
export const readCodexMcpServers = async (
  path: string,
): Promise<McpServers> => {
  const file = Bun.file(path)

  if (!(await file.exists())) {
    return {}
  }

  let config: unknown

  try {
    config = parse(await file.text())
  } catch (error) {
    throw new Error(`Unable to parse Codex config at ${path}`, {
      cause: error,
    })
  }

  if (!isRecord(config) || config.mcp_servers === undefined) {
    return {}
  }

  const servers = config.mcp_servers

  if (!isRecord(servers)) {
    throw new Error(`${path} mcp_servers must be a table`)
  }

  const enabled: McpServers = {}

  for (const [name, server] of Object.entries(servers)) {
    if (!isRecord(server)) {
      throw new Error(`${path} mcp_servers.${name} must be a table`)
    }

    if (server.enabled !== false) {
      enabled[name] = server
    }
  }

  return enabled
}

export type ServerKind = "stdio" | "url" | "invalid"

export const classifyServer = (server: unknown): ServerKind => {
  if (!isRecord(server)) return "invalid"
  if (typeof server.command === "string" && server.command !== "") {
    return "stdio"
  }
  if (typeof server.url === "string" && server.url !== "") return "url"
  return "invalid"
}

/** Paths baked into generated launcher entries. */
export interface LauncherContext {
  bunPath: string
  launcherPath: string
  sourcePath: string
}

export const defaultLauncherContext = (
  sourcePath: string = codexConfigPath(),
): LauncherContext => ({
  bunPath: process.execPath,
  launcherPath: resolve(import.meta.dir, "../claude/mcp-launch.ts"),
  sourcePath: resolve(sourcePath),
})

export const launcherEntry = (
  name: string,
  ctx: LauncherContext,
  target: McpTarget = "claude",
): McpServer => ({
  ...(target === "claude" ? { type: "stdio" } : {}),
  command: ctx.bunPath,
  args: [ctx.launcherPath, "--source", ctx.sourcePath, name],
})

/**
 * Reports whether an entry was generated by this sync. Matching on
 * `claude/mcp-launch.ts` rather than the full path keeps entries from a moved
 * checkout recognizable, so the next sync replaces or removes them.
 */
export const isLauncherEntry = (entry: unknown): boolean => {
  if (!isRecord(entry) || !Array.isArray(entry.args)) {
    return false
  }

  const script = entry.args[0]

  return (
    typeof script === "string" &&
    basename(script) === "mcp-launch.ts" &&
    basename(dirname(script)) === "claude"
  )
}

export type Mapped =
  | { ok: true; entry: McpServer }
  | { ok: false; reason: string }

/**
 * Maps a Codex url server to a Claude or Cursor JSON entry. Env-based auth
 * fields have no JSON equivalent without expanding the secret, so a server
 * that uses them is skipped.
 */
export const codexUrlToJson = (
  server: McpServer,
  target: McpTarget,
): Mapped => {
  for (const field of ["bearer_token_env_var", "env_http_headers"]) {
    if (server[field] !== undefined) {
      return { ok: false, reason: `uses ${field}; add it to ${target} by hand` }
    }
  }

  const headers = server.http_headers

  if (headers !== undefined && !isStringRecord(headers)) {
    return { ok: false, reason: "http_headers values must be strings" }
  }

  return {
    ok: true,
    entry: {
      ...(target === "claude" ? { type: "http" } : {}),
      url: server.url,
      ...(headers && Object.keys(headers).length > 0 ? { headers } : {}),
    },
  }
}

/**
 * Maps a Claude or Cursor JSON entry to a Codex server for ingest. Codex
 * speaks stdio and streamable HTTP, so SSE entries are skipped.
 */
export const jsonToCodex = (entry: unknown): Mapped => {
  if (!isRecord(entry)) return { ok: false, reason: "not an object" }

  if (entry.type === "sse") {
    return { ok: false, reason: "Codex does not support SSE servers" }
  }

  for (const field of ["headersHelper", "oauth"]) {
    if (entry[field] !== undefined) {
      return { ok: false, reason: `uses ${field}, which Codex cannot hold` }
    }
  }

  // Claude `${VAR}` and Cursor `${env:VAR}` expand at load time; Codex and
  // the launcher would pass the placeholder through literally.
  if (JSON.stringify(entry).includes("${")) {
    return { ok: false, reason: "uses ${...} interpolation; add it by hand" }
  }

  const kind = classifyServer(entry)

  if (kind === "stdio") {
    const { args, env, cwd } = entry

    if (args !== undefined && !isStringArray(args)) {
      return { ok: false, reason: "args must be strings" }
    }

    if (env !== undefined && !isStringRecord(env)) {
      return { ok: false, reason: "env values must be strings" }
    }

    if (cwd !== undefined && typeof cwd !== "string") {
      return { ok: false, reason: "cwd must be a string" }
    }

    return {
      ok: true,
      entry: {
        command: entry.command,
        ...(args && args.length > 0 ? { args } : {}),
        ...(env && Object.keys(env).length > 0 ? { env } : {}),
        ...(cwd ? { cwd } : {}),
      },
    }
  }

  if (kind === "url") {
    const headers = entry.headers

    if (headers !== undefined && !isStringRecord(headers)) {
      return { ok: false, reason: "headers values must be strings" }
    }

    return {
      ok: true,
      entry: {
        url: entry.url,
        ...(headers && Object.keys(headers).length > 0
          ? { http_headers: headers }
          : {}),
      },
    }
  }

  return { ok: false, reason: "no command or url" }
}

/** Entries to install in one target, plus servers that cannot be mapped. */
export interface DesiredEntries {
  entries: Record<string, McpServer>
  urlNames: string[]
  skip: { name: string; reason: string }[]
}

const byName = ([a]: [string, unknown], [b]: [string, unknown]): number =>
  a.localeCompare(b)

export const desiredEntries = (
  codexServers: McpServers,
  target: McpTarget,
  ctx: LauncherContext,
): DesiredEntries => {
  const desired: DesiredEntries = { entries: {}, urlNames: [], skip: [] }

  for (const [name, server] of Object.entries(codexServers).sort(byName)) {
    const kind = classifyServer(server)

    if (kind === "stdio") {
      desired.entries[name] = launcherEntry(name, ctx, target)
      continue
    }

    if (kind === "url") {
      const mapped = codexUrlToJson(server, target)

      if (mapped.ok) {
        desired.entries[name] = mapped.entry
        desired.urlNames.push(name)
      } else {
        desired.skip.push({ name, reason: mapped.reason })
      }
      continue
    }

    desired.skip.push({ name, reason: "no command or url" })
  }

  return desired
}

/**
 * Fields that define how Codex reaches and authenticates to a server. Other
 * fields, such as timeouts, are Codex-only settings.
 */
export const transportFields = [
  "command", "args", "env", "env_vars", "cwd", "url", "http_headers",
  "bearer_token_env_var", "env_http_headers",
] as const

export const transportView = (server: McpServer): McpServer =>
  Object.fromEntries(transportFields
    .filter((field) => server[field] !== undefined)
    .map((field) => [field, server[field]]))

const canonical = (value: unknown): string =>
  JSON.stringify(value, (_key, inner: unknown) =>
    isRecord(inner)
      ? Object.fromEntries(
        Object.entries(inner).sort(([a], [b]) => a.localeCompare(b)),
      )
      : inner,
  )

/**
 * Reports whether a Claude or Cursor entry defines the same server as a Codex
 * one, so replacing it loses nothing. Used to skip backups after ingest.
 */
export const heldByCodex = (entry: unknown, codexServer: unknown): boolean => {
  if (!isRecord(codexServer)) return false

  const mapped = jsonToCodex(entry)

  return mapped.ok &&
    canonical(mapped.entry) === canonical(transportView(codexServer))
}
